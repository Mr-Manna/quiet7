/**
 * Generates security-header config from the ACTUAL build output.
 *
 * Why generate instead of hand-writing? The CSP needs a sha256 hash for every
 * inline <script>, and those hashes change whenever the bundler output changes.
 * A hard-coded CSP would silently rot into a broken site (scripts blocked) or a
 * useless one (someone "fixes" it with 'unsafe-inline'). This reads dist/ after
 * every build, so the policy can never drift from reality.
 *
 * Emits, with one identical policy:
 *   dist/_headers                      → Netlify (must live in the publish dir)
 *   vercel.json                        → Vercel (read from the repo root)
 *   docs/nginx-security-headers.conf   → portable / self-hosted
 *
 * Run automatically via the `postbuild` npm script.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = 'dist';

function htmlFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...htmlFiles(p));
    else if (entry.endsWith('.html')) out.push(p);
  }
  return out;
}

// Every inline <script> (i.e. one WITHOUT a src attribute) needs a hash.
const INLINE_SCRIPT = /<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g;

const hashes = new Set();
for (const file of htmlFiles(DIST)) {
  const html = readFileSync(file, 'utf8');
  for (const [, body] of html.matchAll(INLINE_SCRIPT)) {
    if (!body.trim()) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

const scriptSrc = ["'self'", ...[...hashes].sort()].join(' ');

const csp = [
  `default-src 'self'`,
  `script-src ${scriptSrc}`,
  // Astro emits scoped <style> blocks + our @font-face block inline. Hashing
  // styles is far more brittle than scripts and buys little; 'unsafe-inline'
  // for styles only is the accepted trade-off.
  `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' data:`,
  `font-src 'self'`,
  `connect-src 'self'`,
  // The contact form falls back to a mailto: submission when no endpoint is set.
  `form-action 'self' mailto:`,
  `frame-ancestors 'none'`,
  `base-uri 'self'`,
  `object-src 'none'`,
  `upgrade-insecure-requests`,
].join('; ');

const HEADERS = {
  'Content-Security-Policy': csp,
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains; preload',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
};

/* ── Netlify: dist/_headers ─────────────────────────────────────────────── */
const netlify = [
  '# GENERATED by scripts/gen-security-headers.mjs — do not edit by hand.',
  '/*',
  ...Object.entries(HEADERS).map(([k, v]) => `  ${k}: ${v}`),
  '',
  '# Hashed, immutable build assets.',
  '/_astro/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
].join('\n');
writeFileSync(join(DIST, '_headers'), netlify);

/* ── Vercel: vercel.json (repo root) ────────────────────────────────────── */
const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  headers: [
    {
      source: '/(.*)',
      headers: Object.entries(HEADERS).map(([key, value]) => ({ key, value })),
    },
    {
      source: '/_astro/(.*)',
      headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }],
    },
  ],
};
writeFileSync('vercel.json', JSON.stringify(vercel, null, 2) + '\n');

/* ── Portable nginx snippet ─────────────────────────────────────────────── */
mkdirSync('docs', { recursive: true });
const nginx = [
  '# GENERATED by scripts/gen-security-headers.mjs — do not edit by hand.',
  '# Include inside your server { } block.',
  '',
  ...Object.entries(HEADERS).map(([k, v]) => `add_header ${k} "${v}" always;`),
  '',
  'location /_astro/ {',
  '  add_header Cache-Control "public, max-age=31536000, immutable" always;',
  '}',
  '',
].join('\n');
writeFileSync(join('docs', 'nginx-security-headers.conf'), nginx);

console.log(
  `[security-headers] ${hashes.size} inline-script hash(es) → dist/_headers, vercel.json, docs/nginx-security-headers.conf`
);
